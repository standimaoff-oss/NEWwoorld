// Каждый блок — ровно те uniform'ы, которые читает соответствующий .frag/.vert.
export const norm3 = (v) => {
  const l = Math.hypot(v[0], v[1], v[2]) || 1;
  return [v[0] / l, v[1] / l, v[2] / l];
};

