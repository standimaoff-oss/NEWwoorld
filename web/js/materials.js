/** Линейное альбедо → sRGB (для CPU-рендера и отладочных дампов). */
export function toSRGB(c) {
  const f = (x) => (x <= 0.0031308 ? x * 12.92 : 1.055 * Math.pow(Math.max(x, 0), 1 / 2.4) - 0.055);
  return [f(c[0]), f(c[1]), f(c[2])];
}
export function srgb2lin(c) {
  const f = (x) => (x <= 0.04045 ? x / 12.92 : Math.pow((x + 0.055) / 1.055, 2.4));
  return [f(c[0]), f(c[1]), f(c[2])];
}
